// =====================================
// Bot Model:: M
// AutoTrade AI
// مدل دیتابیس ربات
// File: backend/models/Bot.js
// =====================================

import mongoose from "mongoose";


const botSchema = new mongoose.Schema(

    {

        // =====================================
        // مالک ربات:: M
        // =====================================

        userId: {

            type:
                mongoose.Schema.Types.ObjectId,

            ref: "User",

            required: true,

            unique: true,

            index: true

        },


        // =====================================
        // وضعیت ربات:: M
        // =====================================

        status: {

            type: String,

            enum: [

                "ACTIVE",

                "STOPPED",

                "PAUSED",

                "ERROR"

            ],

            default:
                "STOPPED",

            index: true

        },


        // =====================================
        // فعال بودن ربات:: M
        // =====================================

        enabled: {

            type: Boolean,

            default: false,

            index: true

        },


        // =====================================
        // استراتژی معامله:: M
        // =====================================

        strategy: {

            type: String,

            default:
                "AI Scalping",

            trim: true

        },


        // =====================================
        // بازار:: M
        // =====================================

        market: {

            type: String,

            enum: [

                "crypto",

                "forex",

                "stocks",

                "other"

            ],

            default:
                "crypto",

            index: true

        },


        // =====================================
        // سطح ریسک:: M
        // =====================================

        riskLevel: {

            type: String,

            enum: [

                "LOW",

                "MEDIUM",

                "HIGH"

            ],

            default:
                "LOW"

        },


        // =====================================
        // درصد ریسک هر معامله:: M
        // =====================================

        riskPercent: {

            type: Number,

            default: 1,

            min: 0.1,

            max: 5

        },


        // =====================================
        // حداکثر معاملات باز:: M
        // =====================================

        maxOpenTrades: {

            type: Number,

            default: 1,

            min: 1

        },


        // =====================================
        // معاملات باز فعلی:: M
        // =====================================

        openTrades: {

            type: Number,

            default: 0,

            min: 0

        },


        // =====================================
        // حداکثر ضرر متوالی:: M
        // =====================================

        maxConsecutiveLosses: {

            type: Number,

            default: 2,

            min: 1

        },


        // =====================================
        // ضررهای متوالی فعلی:: M
        // =====================================

        consecutiveLosses: {

            type: Number,

            default: 0,

            min: 0

        },


        // =====================================
        // آخرین سیگنال AI:: M
        // =====================================

        lastSignal: {

            type: String,

            enum: [

                "BUY",

                "SELL",

                "HOLD",

                "WAIT"

            ],

            default:
                "WAIT"

        },


        // =====================================
        // زمان آخرین سیگنال:: M
        // =====================================

        lastSignalAt: {

            type: Date,

            default: null

        },


        // =====================================
        // دقت AI:: M
        // =====================================

        accuracy: {

            type: Number,

            default: 0,

            min: 0,

            max: 100

        },


        // =====================================
        // میزان اطمینان AI:: M
        // =====================================

        confidence: {

            type: Number,

            default: 0,

            min: 0,

            max: 100

        },


        // =====================================
        // آخرین اجرای موتور:: M
        // =====================================

        lastRun: {

            type: Date,

            default: null

        },


        // =====================================
        // آخرین ارتباط موتور:: M
        // =====================================

        lastHeartbeat: {

            type: Date,

            default: null

        },


        // =====================================
        // آخرین خطا:: M
        // =====================================

        lastError: {

            type: String,

            default: null

        },


        // =====================================
        // دلیل توقف:: M
        // =====================================

        stopReason: {

            type: String,

            default: ""

        },


        // =====================================
        // آمار کل معاملات:: M
        // =====================================

        totalTrades: {

            type: Number,

            default: 0,

            min: 0

        },


        // =====================================
        // معاملات سودده:: M
        // =====================================

        winningTrades: {

            type: Number,

            default: 0,

            min: 0

        },


        // =====================================
        // معاملات ضررده:: M
        // =====================================

        losingTrades: {

            type: Number,

            default: 0,

            min: 0

        },


        // =====================================
        // مجموع سود و ضرر به دلار:: M
        // =====================================

        totalProfitUSD: {

            type: Number,

            default: 0

        },


        // =====================================
        // نتیجه آخرین معامله به دلار:: M
        // =====================================

        lastTradeProfitUSD: {

            type: Number,

            default: 0

        },


        // =====================================
        // زمان آخرین معامله:: M
        // =====================================

        lastTradeAt: {

            type: Date,

            default: null

        }

    },

    {

        timestamps: true

    }

);


// =====================================
// Bot Model:: M
// ساخت مدل ربات
// =====================================

const Bot =
    mongoose.model(

        "Bot",

        botSchema

    );


export default Bot;
